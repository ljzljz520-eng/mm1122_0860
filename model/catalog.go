func FindMilestone(code string) (Milestone, bool) {
	for _, m := range MilestoneCatalog {
		if m.Code == code {
			return m, true
		}
	}
	return Milestone{}, false
}
func MilestoneWeight(codes []string) int {
	total := 0
	for _, c := range codes {
		if m, ok := FindMilestone(c); ok {
			total += m.Weight
		}
	}
	return total
}
